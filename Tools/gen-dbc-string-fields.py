#!/usr/bin/env python3
"""Regenerates Engine/Source/ModernAssets/Dbc/DbcStringFields.h.

The merge in DbcMerge.cpp has to re-base every string-block offset an add-on row carries. Which
fields those are is not written down anywhere, so it is derived from the one authority the client
itself uses: each `*Rec::Read()` in WoW/Source/DB/Rec, walking its SFileReadFile calls in order and
noting which variable the record later indexes into the string buffer.

The walk reproduces every table's `s_rowSize` exactly; the script fails if it does not, because a
silent mismatch means the offsets would be wrong.

    python Tools/gen-dbc-string-fields.py
"""

import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REC_DIR = os.path.join(ROOT, "WoW", "Source", "DB", "Rec")
OUTPUT = os.path.join(ROOT, "Engine", "Source", "ModernAssets", "Dbc", "DbcStringFields.h")

WIDTHS = {
    "uint8_t": 1, "int8_t": 1, "char": 1,
    "uint16_t": 2, "int16_t": 2,
    "uint32_t": 4, "int32_t": 4, "float": 4,
    "uint64_t": 8, "int64_t": 8,
}


def header_info(path):
    """Member name -> (width, count), plus s_rowSize, read from the record header."""
    text = open(path, encoding="utf-8", errors="ignore").read()
    members = {}
    for m in re.finditer(
            r"/\*\s*[0-9A-Fa-f]{4}\s*\*/\s*([A-Za-z_][\w:<> ]*?)\s+(m_\w+)\s*(?:\[\s*(\d+)\s*\])?\s*;",
            text):
        kind, name, count = m.group(1).strip(), m.group(2), m.group(3)
        members[name] = (WIDTHS.get(kind, 4), int(count) if count else 1)
    row = re.search(r"s_rowSize\s*=\s*(\d+)", text)
    return members, int(row.group(1)) if row else None


def table_name(source):
    m = re.search(r'GetFilename\(\)\s*\{\s*return\s*"DBFilesClient\\\\([^"]+)\.dbc"', source)
    return m.group(1) if m else None


def analyze(cpp_path):
    """Returns (table name, sorted string-field offsets, walk length, s_rowSize)."""
    stem = os.path.basename(cpp_path)[:-4]
    source = open(cpp_path, encoding="utf-8", errors="ignore").read()
    name = table_name(source)
    if not name:
        return None

    members, row_size = header_info(cpp_path[:-4] + ".h")

    body = source[source.find("::Read("):]
    guard = re.search(r"\n\s*if \(", body)
    body = body[:guard.start()] if guard else body

    # Locals the record indexes into the string buffer are exactly its string fields.
    string_vars = set(m.group(1) for m in re.finditer(r"stringBuffer\[\s*([A-Za-z_]\w*)", source))

    locals_ = {}
    for m in re.finditer(r"\b(u?int(?:8|16|32|64)_t|float|char)\s+([A-Za-z_]\w*)\s*(\[\s*(\d+)\s*\])?\s*;", body):
        locals_[m.group(2)] = (WIDTHS[m.group(1)], int(m.group(4)) if m.group(4) else 1)

    position = 0
    fields = []
    for m in re.finditer(
            r"SFileReadFile\(\s*file\s*,\s*&?\s*(?:(this->)([A-Za-z_]\w*)|([A-Za-z_]\w*))"
            r"(?:\s*\[\s*(\d+)\s*\])?\s*,\s*(sizeof\(\s*[^)]*\)|\d+)\s*,", body):
        var = m.group(2) or m.group(3)
        size_argument = m.group(5)

        if size_argument.startswith("sizeof"):
            inner = re.sub(r"\s+", "", size_argument[7:-1]).replace("this->", "").lstrip("&")
            if "[" in inner:
                advance = 4  # one element of a locale array
            elif inner in members:
                advance = members[inner][0] * members[inner][1]
            elif inner in locals_:
                advance = locals_[inner][0] * locals_[inner][1]
            else:
                advance = 4
        else:
            advance = int(size_argument)

        if var in string_vars:
            fields.append(position)
        position += advance

    return name, sorted(set(fields)), position, row_size


def main():
    results = {}
    failures = []

    for cpp in sorted(glob.glob(os.path.join(REC_DIR, "*.cpp"))):
        analyzed = analyze(cpp)
        if not analyzed:
            continue
        name, fields, walked, row_size = analyzed
        results[name] = fields
        if row_size is not None and walked != row_size:
            failures.append("%s: walk %d != s_rowSize %d" % (name, walked, row_size))
        if fields and fields[-1] + 4 > (row_size or 0):
            failures.append("%s: string field past the row" % name)

    if failures:
        for line in failures:
            print("ERROR:", line, file=sys.stderr)
        print("Refusing to write: the derived offsets are not trustworthy.", file=sys.stderr)
        return 1

    lines = [
        "// GENERATED by Tools/gen-dbc-string-fields.py -- do not edit by hand.",
        "//",
        "// Byte offsets, within a row, of every field the stock client reads as a string-block offset.",
        "// Derived from each `*Rec::Read()` in WoW/Source/DB/Rec (the order it calls SFileReadFile), so the",
        "// table is the same walk that fills the record at load time. Every entry was checked to land inside",
        "// that table's `s_rowSize`, and the full walk of each table reproduces `s_rowSize` exactly.",
        "//",
        "// Why it must be complete: an appended add-on row carries offsets into ITS OWN string block. A field",
        "// missing here is copied through verbatim and then indexes the base table's block, which is what",
        "// printed garbage into item and spell tooltips.",
        "",
        "#ifndef ENGINE_SOURCE_MODERNASSETS_DBC_DBCSTRINGFIELDS_H",
        "#define ENGINE_SOURCE_MODERNASSETS_DBC_DBCSTRINGFIELDS_H",
        "",
        "#include <cstdint>",
        "#include <string>",
        "#include <unordered_map>",
        "#include <vector>",
        "",
        "namespace modern::dbc",
        "{",
        "    /// Row-field offsets holding string-block offsets, keyed by table name (no directory, no extension).",
        "    inline const std::unordered_map<std::string, std::vector<uint32_t>>& StringFieldTable()",
        "    {",
        "        static const std::unordered_map<std::string, std::vector<uint32_t>> kFields = {",
    ]
    for name in sorted(results):
        values = ", ".join(str(v) for v in results[name])
        lines.append('            { "%s", { %s } },' % (name, values))
    lines += [
        "        };",
        "        return kFields;",
        "    }",
        "}",
        "",
        "#endif",
        "",
    ]

    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))

    print("wrote %s (%d tables)" % (os.path.relpath(OUTPUT, ROOT), len(results)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
